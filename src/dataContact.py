# ==========================================
# Desafio 01 - Concatenar Dados
# ==========================================
# Descrição:
# Receba dois dados informados pelo usuário
# e concatene-os em uma única string.
# ==========================================

# Entrada de dados
texto1 = input("Digite o primeiro texto: ")
texto2 = input("Digite o segundo texto: ")

# Concatenação
resultado = f"{texto1} {texto2}"

# Saída
print("\nResultado:")
print(resultado)
